import { buildElectron } from './build-electron.mjs';
import { _electron } from 'playwright-core';
import electron from 'electron';
import { createServer } from 'vite';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';

const temp = path.join(process.env.LOCALAPPDATA, 'Temp', 'opencode');
const profile = await fs.mkdtemp(path.join(temp, 'board-check-'));
const evidence = path.join(temp, 'subcal-board-evidence');
await fs.mkdir(evidence, { recursive: true });
await buildElectron();
const server = await createServer({ cacheDir: path.join(profile, 'vite'), server: { port: 0, strictPort: false, hmr: false } });
await server.listen();
const env = { ...process.env, SUBCAL_USER_DATA: profile, SUBCAL_DEV_URL: server.resolvedUrls.local[0] };
delete env.ELECTRON_RUN_AS_NODE;
let app;
const errors = [];
try {
  app = await _electron.launch({ executablePath: electron, args: ['.'], env });
  const page = await app.firstWindow();
  page.on('pageerror', (error) => errors.push(error.message));
  await page.getByRole('button', { name: '添加订阅', exact: true }).first().click();
  await page.getByRole('button', { name: '手动记录其他订阅', exact: true }).click();
  await page.locator('#sub-product').fill('价格回归验证');
  await page.locator('#sub-price').fill('120');
  await page.locator('#sub-renewal-date').fill('2026-12-01');
  await page.getByRole('button', { name: '保存手动记录', exact: true }).click();
  await page.getByRole('button', { name: '编辑记录', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await page.locator('.board-price').filter({ hasText: '120.00' }).waitFor();
  assert.match(await page.locator('.board-total').innerText(), /120.00/);
  console.log('PASS real SQLite create and price summary');

  await app.evaluate(async ({ BrowserWindow }, url) => BrowserWindow.getAllWindows()[0].loadURL(url), `${server.resolvedUrls.local[0]}?mode=preview`);
  await page.locator('.board-card').first().waitFor();
  const scenario = async (id) => {
    await page.evaluate(async (value) => (await import('/src/renderer/service/client.ts')).client.preview.switchScenario(value), id);
    await page.waitForFunction((value) => document.querySelector('.app')?.getAttribute('data-scenario') === value, id);
  };
  assert.match(await page.locator('.board-total').innerText(), /50.00/);
  await page.getByRole('button', { name: '已用', exact: true }).click();
  await page.locator('[data-card-id="openrouter"]').getByText(/已用.*26.25/).waitFor();
  await page.locator('[data-card-id="deepseek"]').getByText('已用量未知').first().waitFor();
  console.log('PASS used amount is total minus remaining; unknown stays unknown');
  await scenario('multi_account_shared');
  await page.getByLabel('Kimi API 切换账号').selectOption('kimi-3');
  assert.equal(await page.locator('[data-card-id="kimi-3"]').count(), 1);
  await page.getByRole('button', { name: '剩余', exact: true }).click();
  await page.locator('[data-card-id="kimi-3"]').getByText(/150.00/).waitFor();
  await page.getByLabel('搜索订阅', { exact: true }).fill('团队示例账号 2');
  await page.locator('[data-card-id="kimi-2"]').waitFor();
  assert.equal(await page.locator('.board-card').count(), 1);
  await page.getByLabel('搜索订阅', { exact: true }).fill('');
  console.log('PASS multi-account switching and account search');
  await scenario('unknown_and_na');
  assert.match(await page.locator('.board-total').innerText(), /1 项价格未知，未计入/);
  await scenario('date_boundaries');
  assert.match(await page.locator('.board-total').innerText(), /44.00/);
  assert.match(await page.locator('[data-card-id="leap"] .board-price').innerText(), /120.00\/年/);
  console.log('PASS unknown prices and yearly normalization');
  await scenario('stale_and_past_reset');
  await page.locator('[data-card-id="codex"]').getByText('待核实').waitFor();
  assert.ok(await page.getByText('数据已过时 · 待更新').count() > 0);
  await page.evaluate(async () => {
    const { client } = await import('/src/renderer/service/client.ts');
    const sub = (await client.snapshot()).subscriptions.find((s) => s.id === 'claude');
    await client.update(sub.id, sub.revision, { lifecycle: 'archived' });
  });
  await page.getByRole('button', { name: '已归档', exact: true }).click();
  await page.locator('[data-card-id="claude"]').waitFor();
  await page.locator('[data-card-id="claude"] .board-card-title').click();
  await page.getByRole('button', { name: '恢复活跃跟踪', exact: true }).click();
  await page.getByRole('button', { name: '确认恢复', exact: true }).click();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: '当前订阅', exact: true }).click();
  await scenario('normal_mixed');
  await page.screenshot({ path: path.join(evidence, 'board-light.png') });
  await page.getByRole('button', { name: '切换深浅色主题' }).click();
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
  await page.screenshot({ path: path.join(evidence, 'board-dark.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '打开导航菜单' }).click();
  await page.getByRole('dialog', { name: '导航菜单' }).getByRole('button', { name: '设置', exact: true }).click();
  await page.getByRole('button', { name: '打开导航菜单' }).click();
  await page.getByRole('dialog', { name: '导航菜单' }).locator('nav button').last().click();
  assert.equal(await page.getByRole('dialog', { name: '导航菜单' }).count(), 0);
  await page.getByRole('button', { name: '打开导航菜单' }).click();
  await page.getByRole('dialog', { name: '导航菜单' }).getByRole('button', { name: '返回', exact: true }).click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  await page.screenshot({ path: path.join(evidence, 'board-mobile.png') });
  assert.deepEqual(errors, []);
  console.log(`PASS archived access, stale states, themes, mobile navigation; screenshots: ${evidence}`);
} finally {
  await app?.close();
  await server.close();
  await fs.rm(profile, { recursive: true, force: true });
}
